/**
 * - `headerOf`, `bulletsOf` · a file's opening block, its bullets: its job in 1–3
 * - `PROLOGUE`, `isGenerated` · what may stand above them; a file a tool writes
 * - `MOST_BULLETS`, `LONGEST_BULLET` · how many bullets, and how long each
 */

const MOST_BULLETS = 3;
const LONGEST_BULLET = 80;
const OPENS = '/**\n';
// a bullet's text starts at its first mark, so no space is read twice
const A_BULLET = /^\s*\*\s+-\s+(\S.*)$/;
// a shebang, then a directive (`'use client';`): the lines a header may sit under
const PROLOGUE = /^(?:#![^\n]*\n)?(?:\s*(['"])use [a-z ]+\1;?[^\S\n]*\n)*\s*/;

const isGenerated = (text: string): boolean =>
  /^(\/\/[^\n]*\n)*\/\/ GENERATED by /.test(text.replace(PROLOGUE, ''));

// a text's opening `/** … */` to its first `*/`: the whole, and what stands inside; null when none opens it
function headerOf(
  text: string,
): { readonly whole: string; readonly inside: string } | null {
  if (!text.startsWith(OPENS)) return null;
  const end = text.indexOf('*/', OPENS.length);
  return end === -1
    ? null
    : { whole: text.slice(0, end + 2), inside: text.slice(OPENS.length, end) };
}

// null when the file opens with no header, or with a line that is no bullet
const bulletsOf = (text: string): readonly string[] | null => {
  const block = headerOf(text.replace(PROLOGUE, ''))?.inside;
  if (block === undefined) return null;
  const bullets = block
    .split('\n')
    .filter((line) => line.replace(/^\s*\*?\s*/, '') !== '')
    .map((line) => A_BULLET.exec(line)?.[1]);
  return bullets.every((bullet) => bullet !== undefined)
    ? bullets.flatMap((one) => one ?? [])
    : null;
};

export {
  bulletsOf,
  headerOf,
  isGenerated,
  LONGEST_BULLET,
  MOST_BULLETS,
  PROLOGUE,
};

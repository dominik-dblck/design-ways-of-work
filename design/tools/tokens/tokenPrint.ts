/**
 * - `tokensModule` · tokens, faces, element styles, reduced motion: one module
 * - every var() resolved at build, so a jsdom test can measure a colour
 * - an alias whose target the dark block flips stays an alias, to follow
 */
import type { ElementStyle } from '../../design-system/index.ts';

const ALIAS = /^var\(\s*(--[\w-]+)\s*\)$/;

interface Lookup {
  readonly lookups: readonly ReadonlyMap<string, string>[];
  readonly flips: ReadonlySet<string>;
  readonly seen: readonly string[];
}

const keyOf = (name: string): string => {
  const [first = '', ...rest] = name.replace(/^--/, '').split('-');
  return (
    first +
    rest.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('')
  );
};

function resolve(cssValue: string, at: Lookup): string {
  const alias = ALIAS.exec(cssValue.trim());
  if (alias?.[1] !== undefined && at.flips.has(alias[1]))
    return cssValue.trim();
  return cssValue.replace(
    /var\(\s*(--[\w-]+)\s*(?:,([^()]*))?\)/g,
    (_all, name: string, fallback: string | undefined) => {
      if (at.seen.includes(name))
        throw new Error(
          `${name} · a var() cycle · ${[...at.seen, name].join(' → ')}`,
        );
      const held = at.lookups.find((map) => map.has(name))?.get(name);
      if (held !== undefined)
        return resolve(held, { ...at, seen: [...at.seen, name] });
      if (fallback !== undefined) return resolve(fallback.trim(), at);
      throw new Error(`${name} · referenced and never declared`);
    },
  );
}

const typed = (cssValue: string): string | number => {
  const px = /^(-?\d+(?:\.\d+)?)px$/.exec(cssValue);
  if (px?.[1] !== undefined) return Number(px[1]);
  return /^-?\d+(?:\.\d+)?$/.test(cssValue) ? Number(cssValue) : cssValue;
};

const line = (key: string, tokenValue: string | number): string =>
  `    ${key}: ${typeof tokenValue === 'number' ? tokenValue : JSON.stringify(tokenValue)},`;

const HEADER = `// GENERATED by tools/tokens.ts from design-system/ and app/styles/productTokens.ts.
// Do not edit: edit the token's row, then run \`node tools/build.ts\`.
//
// Every reference is resolved at build rather than at paint, so the theme is readable without a
// stylesheet — which is what lets a jsdom test measure a colour.

/** A resolved token · a hex, a px number, or a string a filter or a shadow needs. */
export type TokenValue = string | number;
`;

const FOOTER = `
export type LightToken = keyof typeof tokens.light;
export type DarkToken = keyof typeof tokens.dark;

/** The two blocks this file holds · the one spelling of a mode, derived rather than written. */
export type Mode = keyof typeof tokens;
`;

type Face = Readonly<Record<string, string | number>>;

// a face as one line: its fields in the order the system writes them
const faceLine = (face: Face): string =>
  `  { ${Object.entries(face)
    .map(([key, held]) => `${key}: ${JSON.stringify(held)}`)
    .join(', ')} },`;

// the faces as the module's own export, in the order the system lists them
const facesBlock = (faces: readonly Face[]): string => `
/** Each face of the families · its file under the design system's \`fonts/\`. */
export const faces = [
${faces.map(faceLine).join('\n')}
] as const;
`;

// each value a token takes when the person asks for less motion, keyed as the tokens are
const reducedBlock = (reduced: ReadonlyMap<string, string>): string => `
/** A token's value under \`prefers-reduced-motion: reduce\` · every other token keeps its own. */
export const reducedMotion = {
${[...reduced].map(([name, cssValue]) => line(keyOf(name), typed(cssValue))).join('\n')}
} as const;
`;

// the styles an element or a class takes, each declaration as the system writes it
const elementsBlock = (styles: readonly ElementStyle[]): string => `
/** Each element or class the system styles · its declarations as written, var() kept. */
export const elements = [
${styles.map((one) => `  { selector: ${JSON.stringify(one.selector)}, style: ${JSON.stringify(one.style)} },`).join('\n')}
] as const;
`;

interface Sources {
  readonly light: ReadonlyMap<string, string>;
  readonly dark: ReadonlyMap<string, string>;
  readonly faces: readonly Face[];
  readonly reducedMotion: ReadonlyMap<string, string>;
  readonly elements: readonly ElementStyle[];
}

function tokensModule(sources: Sources): string {
  const { light, dark, faces, reducedMotion, elements } = sources;
  const flips = new Set(dark.keys());
  const block = (
    source: ReadonlyMap<string, string>,
    lookups: Lookup['lookups'],
  ): string =>
    [...source]
      .map(([name, cssValue]) =>
        line(
          keyOf(name),
          typed(resolve(cssValue, { lookups, flips, seen: [] })),
        ),
      )
      .join('\n');
  const names = [...light.keys()]
    .map((name) => `  ${keyOf(name)}: ${JSON.stringify(name)},`)
    .join('\n');
  return `${HEADER}
export const tokens = {
  light: {
${block(light, [light])}
  },
  dark: {
${block(dark, [dark, light])}
  },
} as const;

/** The CSS variable each key was read from · \`bgPrimary\` → \`--bg-primary\`. */
export const TOKEN_NAMES: Record<keyof typeof tokens.light, string> = {
${names}
};
${facesBlock(faces)}${reducedBlock(reducedMotion)}${elementsBlock(elements)}${FOOTER}`;
}

export { tokensModule };

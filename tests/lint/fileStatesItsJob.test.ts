import { fileStatesItsJob } from '../../shared/lint/rules/fileStatesItsJob.ts';
import { ruleTester } from './ruleTester.ts';

const FILE = 'sheet/words/planted.ts';
const ENTRY = [{ entries: [FILE] }] as const;
const job = (what: string) => ({ messageId: 'job' as const, data: { what } });
const VALUE_NAMES = Array.from({ length: 16 }, (_, at) => `value${at}`);
const passingOn = (bullet: string) =>
  `/**\n * - ${bullet}\n */\nimport { ${VALUE_NAMES.map((name) => name.toUpperCase()).join(', ')} } from './planted/rows.ts';\nexport { ${VALUE_NAMES.map((name) => `${name.toUpperCase()} as ${name}`).join(', ')} };`;

ruleTester.run('file-states-its-job', fileStatesItsJob, {
  valid: [
    {
      name: "a header under 'use client'; a default export needs no bullet",
      filename: 'app/page.tsx',
      code: "'use client';\n/**\n * - the page: the board\n */\nexport default function Page(): null { return null; }",
    },
    {
      name: 'a file a tool writes',
      filename: FILE,
      code: '// GENERATED by tools/emit.ts\nexport const ONE = 1;',
    },
    {
      name: 'a .tsx entry passing on its part names the part',
      filename: 'app/planted.tsx',
      options: [{ entries: ['app/planted.tsx'] }],
      code: "/**\n * - `rows` · the planted rows\n */\nimport { ROWS } from './planted/rows.tsx';\nexport { ROWS as rows };",
    },
    {
      name: 'an entry naming its API under the names it exports',
      filename: FILE,
      options: ENTRY,
      code: "/**\n * - `all`, `byId` · the pages and each one by its id\n */\nimport { PAGES } from './planted/pages.ts';\nconst byId = {};\nexport { PAGES as all, byId };",
    },
    {
      name: "an entry passing on its part names the part; its sixteen values are the part's",
      filename: FILE,
      options: ENTRY,
      code: passingOn('`rows` · the planted rows'),
    },
  ],
  invalid: [
    {
      name: 'no header',
      filename: FILE,
      code: 'export const ONE = 1;',
      errors: [job('no header of 1–3 bullets')],
    },
    {
      name: 'a free-text header',
      filename: FILE,
      code: '// planted.ts\nexport const ONE = 1;',
      errors: [job('no header of 1–3 bullets')],
    },
    {
      name: 'a fourth bullet',
      filename: FILE,
      code: '/**\n * - `ONE`\n * - b\n * - c\n * - d\n */\nexport const ONE = 1;',
      errors: [job('no header of 1–3 bullets')],
    },
    {
      name: 'a long bullet, an export no bullet names, a name the file lacks',
      filename: FILE,
      code: `/**\n * - \`ONE\` and \`gone\`\n * - ${'x'.repeat(81)}\n */\nexport const ONE = 1;\nexport function two(): number { return 2; }\nexport type Three = 3;`,
      errors: [
        job('a bullet of 81 characters'),
        job('`two` in no bullet'),
        job('`gone` not in the file'),
      ],
    },
    {
      name: 'an entry passing on its part without naming it',
      filename: FILE,
      options: ENTRY,
      code: passingOn('the planted rows'),
      errors: VALUE_NAMES.map((name) => job(`\`${name}\` in no bullet`)),
    },
    {
      name: 'sixteen exported values',
      filename: FILE,
      code: `/**\n * - ${VALUE_NAMES.map((name) => `\`${name}\``).join(' ')}\n */\n${VALUE_NAMES.map((name) => `export const ${name} = 1;`).join('\n')}`,
      errors: [
        job('16 exported values'),
        job(
          `a bullet of ${VALUE_NAMES.map((name) => `\`${name}\``).join(' ').length} characters`,
        ),
      ],
    },
  ],
});
